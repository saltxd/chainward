import { OFAC_SNAPSHOT } from './ofac-snapshot.js';

/**
 * US Treasury OFAC sanctions screening for EVM addresses.
 *
 * The Specially Designated Nationals (SDN) list names digital currency addresses
 * per asset tag. An EVM address is the same key on every EVM chain, so an address
 * listed under ETH, ARB, BSC (or an ERC-20 tag like USDT) is sanctioned on Base
 * and BNB Chain too. The machine-readable feed is 0xB10C's nightly extract of the
 * SDN XML; scripts/update-ofac-list.ts turns it into the bundled snapshot below,
 * so the check works offline and every change to the list is a reviewed diff.
 */

export const OFAC_LIST_SOURCE = 'https://github.com/0xB10C/ofac-sanctioned-digital-currency-addresses';
/** Treasury's own search page, cited on the flag. */
export const OFAC_SEARCH_URL = 'https://sanctionssearch.ofac.treas.gov/';

/**
 * The asset tags whose addresses are EVM-format. USDC and USDT are tokens on many
 * chains, so their files also carry Tron / Omni addresses, which are skipped.
 */
export const OFAC_LIST_FILES: readonly { asset: string; skipNonEvm: boolean }[] = [
  { asset: 'ETH', skipNonEvm: false },
  { asset: 'ETC', skipNonEvm: false },
  { asset: 'ARB', skipNonEvm: false },
  { asset: 'BSC', skipNonEvm: false },
  { asset: 'USDC', skipNonEvm: true },
  { asset: 'USDT', skipNonEvm: true },
];

export function ofacListUrl(asset: string): string {
  return `https://raw.githubusercontent.com/0xB10C/ofac-sanctioned-digital-currency-addresses/lists/sanctioned_addresses_${asset}.txt`;
}

const EVM_ADDRESS = /^0x[0-9a-fA-F]{40}$/;

/**
 * One list file, validated: every non-blank line must be 0x + 40 hex, or the
 * whole file is refused (a truncated or reformatted download must never shrink
 * the list quietly). `skipNonEvm` drops lines that are not 0x-prefixed at all,
 * for the multi-chain token files. Returns lowercased, deduped, sorted.
 */
export function parseOfacList(text: string, opts: { skipNonEvm?: boolean } = {}): string[] {
  const out = new Set<string>();
  text.split('\n').forEach((raw, i) => {
    const line = raw.trim();
    if (line === '') return;
    if (opts.skipNonEvm && !/^0x/i.test(line)) return;
    if (!EVM_ADDRESS.test(line)) {
      throw new Error(`OFAC list line ${i + 1} is not a 0x address: ${JSON.stringify(line.slice(0, 60))}`);
    }
    out.add(line.toLowerCase());
  });
  return [...out].sort();
}

/** The TypeScript source of ofac-snapshot.ts, as the update script writes it. */
export function renderOfacSnapshot(addresses: readonly string[], fetchedAt: string): string {
  const files = OFAC_LIST_FILES.map((f) => f.asset).join(',');
  return [
    '// Generated by scripts/update-ofac-list.ts (pnpm ofac:update). Do not edit by hand.',
    '//',
    '// US Treasury OFAC SDN list, digital currency addresses in EVM format.',
    `// Source: ${OFAC_LIST_SOURCE}`,
    `//   lists branch, sanctioned_addresses_{${files}}.txt (0x entries only)`,
    `// Fetched: ${fetchedAt}`,
    '',
    'export const OFAC_SNAPSHOT: { source: string; fetched_at: string; addresses: readonly string[] } = {',
    `  source: '${OFAC_LIST_SOURCE}',`,
    `  fetched_at: '${fetchedAt}',`,
    '  addresses: [',
    ...addresses.map((a) => `    '${a}',`),
    '  ],',
    '};',
    '',
  ].join('\n');
}

const SANCTIONED: ReadonlySet<string> = new Set(OFAC_SNAPSHOT.addresses);

/** True when the address is on the bundled OFAC SDN snapshot. Case-insensitive. */
export function isSanctioned(address: string): boolean {
  return SANCTIONED.has(address.toLowerCase());
}
